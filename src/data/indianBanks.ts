export function searchIndianBanks(query: string): IndianBank[] {
  const q = query.trim().toLowerCase();
  if (!q) return INDIAN_BANKS;
  return INDIAN_BANKS.filter(
    (b) =>
      b.name.toLowerCase().includes(q) ||
      b.shortName.toLowerCase().includes(q) ||
      b.category.toLowerCase().includes(q) ||
      (b.gpaySuffix && b.gpaySuffix.toLowerCase().includes(q)) ||
      (b.phonepeSuffix && b.phonepeSuffix.toLowerCase().includes(q))
  );
}
